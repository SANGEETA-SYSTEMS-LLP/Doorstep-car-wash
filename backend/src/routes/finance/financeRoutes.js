import express from "express";
import { requireAuth } from "../../middleware/authMiddleware.js";
import { cancelDraft, requireFinanceRole, listOperations, listWasherPayouts, createOperation, reconcileOperation, savePayoutAccount, getWasherPayoutMethod, getFinanceProviderStatus } from "../../controllers/finance/financeController.js";
import { getInvoice, getReport } from "../../controllers/finance/financeDocumentsController.js";
import { paymentActionRateLimit } from "../../middleware/rateLimitMiddleware.js";
const router=express.Router();
router.use(requireAuth);
router.get("/invoices/:bookingId",getInvoice);
router.use(requireFinanceRole);
router.get("/provider-status",getFinanceProviderStatus);
router.get("/operations",listOperations);
router.get("/washer-payouts",listWasherPayouts);
router.post("/operations",paymentActionRateLimit,createOperation);
router.post("/operations/:id/reconcile",paymentActionRateLimit,reconcileOperation);
router.post("/operations/:id/cancel",paymentActionRateLimit,cancelDraft);
router.get("/payout-account/:washerId",getWasherPayoutMethod);
router.put("/payout-account",savePayoutAccount);
router.get("/reports",getReport);
export default router;
