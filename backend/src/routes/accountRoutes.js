import express from "express";
import { getProfileLocation, saveProfileLocation, getNearbyWashers } from "../controllers/washerLocationProfileController.js";
import { getWasherPayout, saveWasherPayout } from "../controllers/washerPayoutController.js";
import { requireAuth } from "../middleware/authMiddleware.js";
import { getAccount, updateAccount, myEarnings, myEarningsSummary, myEarningsLifetimeSummary, getCustomerResources, getMyBookings } from "../controllers/accountController.js";
import { saveAddress, updateAddress, deleteAddress } from "../controllers/customerAddressController.js";
import { createCustomerVehicle, deleteCustomerVehicle } from "../controllers/customerVehicleController.js";
import { ensureMonthlyWashPackages, ensureOneTimeWashPackages, listPackages, validatePackage } from "../controllers/packageController.js";
import { listCustomerOffers, validateCustomerOffer } from "../controllers/customerOfferController.js";
import { allowRoles } from "../middleware/roleMiddleware.js";
const router = express.Router();
router.use(requireAuth);
router.get("/washer-location", getProfileLocation);
router.put("/washer-location", saveProfileLocation);
router.get("/nearby-washers", getNearbyWashers);
router.get("/payout-account", getWasherPayout);
router.put("/payout-account", saveWasherPayout);
router.get("/bookings", getMyBookings);
router.get("/packages", listPackages);
router.post("/packages/monthly-plans", allowRoles("customer"), ensureMonthlyWashPackages);
router.post("/packages/one-time-tiers", allowRoles("customer"), ensureOneTimeWashPackages);
router.post("/packages/validate", validatePackage);
router.get("/offers", allowRoles("customer"), listCustomerOffers);
router.post("/offers/validate", allowRoles("customer"), validateCustomerOffer);
router.post("/vehicles", createCustomerVehicle);
router.delete("/vehicles/:id", deleteCustomerVehicle);
router.post("/addresses", saveAddress);
router.patch("/addresses/:id", updateAddress);
router.delete("/addresses/:id", deleteAddress);
router.get("/customer/:resource", getCustomerResources);
router.get("/profile", getAccount);
router.patch("/profile", updateAccount);
router.get("/earnings", myEarnings);
router.get("/earnings/summary", myEarningsSummary);
router.get("/earnings/lifetime-summary", myEarningsLifetimeSummary);
export default router;
